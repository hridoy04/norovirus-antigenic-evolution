# ── NODE NAMING ───────────────────────────────────────────────────────────

#  The antigenicity scan names internal nodes NODE_0000000 upward, starting
#  at the root, while the tree numbers them from Ntip + 1 upward. On the
#  current tree (1183 tips) root node 1184 is NODE_0000000, so the offset is
#  Ntip + 1. Verified: all 129 node names in the combined table round-trip.
node_offset <- function(tree) ape::Ntip(as.phylo(tree)) + 1L

node_to_name <- function(node, tree) sprintf("NODE_%07d", node - node_offset(tree))

name_to_node <- function(name, tree) {
  as.integer(str_remove(name, "^NODE_")) + node_offset(tree)
}


# ── 1. DEEP NODES ─────────────────────────────────────────────────────────

#' Topmost nodes of clades with a certain inferred state.
#'
#' Reads the BEAST `location.set` / `location.set.prob` annotations, splits
#' internal nodes into pure-acute, pure-chronic and mixed/uncertain, then
#' reduces each set to its clade roots.
#'
#' @param x A `noro_deepnode` object, or a treedata from `read.beast()`.
#' @param method How a clade root is identified.
#'   "ancestor" (default, correct): a node with no ancestor in the same set.
#'   "runs" (legacy): the original code split the set into runs of consecutive
#'     node numbers and looked for ancestors only within each run. Node
#'     numbers are not contiguous per clade, so a node whose ancestor fell in
#'     a different run was wrongly reported as a clade root.
#'
#'   The two agree exactly where a set is scattered across the tree
#'   (chronic: 24 nodes either way) and diverge where a set contains the root
#'   (acute: 1 vs 79; mixed: 1 vs 42). "runs" is kept only to reproduce old
#'   output -- prefer "ancestor".
find_deep_nodes <- function(x, method = c("ancestor", "runs")) {
  method <- match.arg(method)
  tree   <- as_tree(x)

  internal <- tree %>%
    as_tibble() %>%
    mutate(
      location.set      = lapply(location.set, as.character),
      location.set.prob = lapply(location.set.prob, as.numeric)
    ) %>%
    unnest(c(location.set, location.set.prob)) %>%
    filter(is.na(label))          # tips carry a label, internal nodes do not

  pure <- function(state) {
    internal %>%
      filter(location.set == state, location.set.prob == 1) %>%
      pull(node)
  }

  #  Mixed = appears in the table but never with probability 1, i.e. no single
  #  state is certain at that node.
  certain <- internal %>% filter(location.set.prob == 1) %>% pull(node) %>% unique()
  mixed   <- setdiff(unique(internal$node), certain)

  roots <- switch(method,
    ancestor = function(nodes) {
      if (!length(nodes)) return(integer(0))
      nodes[!vapply(nodes,
                    function(nd) any(ancestor(tree, nd) %in% nodes),
                    logical(1))]
    },
    runs = function(nodes) {
      if (!length(nodes)) return(integer(0))
      grp <- split(nodes, cumsum(c(1, diff(nodes) != 1)))
      unlist(lapply(grp, function(g) {
        g[lengths(lapply(g, function(nd) {
          a <- ancestor(tree, nd); a[a %in% g]
        })) == 0]
      }), use.names = FALSE)
    }
  )

  list(
    acute   = sort(roots(pure("acute"))),
    chronic = sort(roots(pure("chronic"))),
    mixed   = sort(roots(mixed))
  )
}


# ── 2. NODE OFFSPRING ─────────────────────────────────────────────────────

#' Every internal node with its date, inferred state and descendant tips.
#'
#' One row per (internal node, descendant tip). `offspring(type = "tips")`
#' does the tip-only filtering at source, so internal nodes never enter the
#' output -- no separate removal step is needed.
#'
#' @param mrsd Most recent sampling date: a decimal year, or anything
#'   `as.Date()` parses. BEAST `height` is time before the most recent
#'   sample, so date = mrsd - height. Both must be in years.
node_offspring <- function(tree, mrsd = NORO_MRSD) {
  mrsd_dec <- as_decimal_year(mrsd)

  tree_tbl  <- as_tibble(tree)
  tip_names <- tree_tbl %>% select(node, id = label)

  tree_tbl %>%
    filter(is.na(label)) %>%
    transmute(
      node,
      clinical_state = location,
      date           = mrsd_dec - as.numeric(height),
      offspring      = map(node, ~ offspring(tree, .x, type = "tips"))
    ) %>%
    unnest_longer(offspring) %>%
    left_join(tip_names, by = c("offspring" = "node")) %>%
    mutate(ancestor_node = node_to_name(node, tree))
}

as_decimal_year <- function(mrsd) {
  if (is.numeric(mrsd)) mrsd else lubridate::decimal_date(as.Date(mrsd))
}


# ── 3. PREDICTED ANTIGENIC SUBSTITUTIONS ──────────────────────────────────

#' Read the EpAL / ESM-2 scan and reduce it to one substitution per site.
#'
#' See the header for why the slice comes before the label filter. Returns one
#' row per (node, position) that survives all three steps.
#'
#' @param path cna.csv, 15 columns, named positionally via CNA_COLS.
#' @param sa_min Minimum relative surface accessibility.
read_antigenicity <- function(path = NORO_PATHS$antigenicity,
                              sa_min = NORO_SA_MIN) {

  raw <- fread(path, skip = 1, header = FALSE, showProgress = FALSE,
               col.names = CNA_COLS) %>%
    as_tibble() %>%
    #  cna.csv carries repeated header rows part-way through the file; they
    #  would otherwise become NA rows after the numeric coercion below.
    filter(position != "position") %>%
    mutate(across(c(position, surface_accessibility, cand_antigenicity,
                    aa_change_likelihood), as.numeric))

  raw %>%
    group_by(node, position) %>%
    #  with_ties = TRUE is load-bearing, not laziness. Sites where several
    #  candidates share the top antigenicity are common, and step 2 is what
    #  resolves them: the question is whether the ESM-2 substitution is AMONG
    #  the top-scoring candidates. Forcing one arbitrary winner here loses 771
    #  of 2,770 sites on the current file.
    slice_max(cand_antigenicity, na_rm = TRUE) %>%                     # 1. most antigenic candidate(s)
    ungroup() %>%
    filter(cand_label == obs_label) %>%                                # 2. and the ESM-2 one is there
    filter(surface_accessibility >= sa_min) %>%                        # 3. and it is exposed
    transmute(
      virus_name = node,                     # NODE_xxxxxxx, joins to ancestor_node
      position,
      ref,
      alt   = cand_alt,
      epal  = cand_antigenicity,
      label = cand_label,
      surface_accessibility,
      aa_change_likelihood
    ) %>%
    arrange(virus_name, position)
}

#' Collapse the per-site predictions to one row per node, with list columns.
antigenicity_by_node <- function(pred) {
  pred %>%
    group_by(virus_name) %>%
    summarise(pos = list(position), mutation_pred = list(label), .groups = "drop")
}


# ── 4. OBSERVED MUTATIONS ─────────────────────────────────────────────────

#' Read observed mutations per sequence and parse them into list columns.
#'
#' The file holds one row per sequence plus the RefSeq row, with `mutation` as
#' text like "[A123B, C45D]" ("[]" when none). The regex pulls out the codes,
#' giving character(0) for an empty list.
#' `.obs_order` is the file's own row order. It is kept because the original
#' script picked each node's representative tip with a right_join followed by
#' distinct(), which made the choice depend on this order -- see
#' `tip_mutations = "first"` below.
read_mutations <- function(path = NORO_PATHS$mutations) {
  read_csv(path, show_col_types = FALSE) %>%
    transmute(id,
              mutation_real = str_extract_all(mutation, MUT_RX),
              .obs_order    = row_number())
}


# ── 5. THE COMBINED TABLE ─────────────────────────────────────────────────

#' Build `noro_deepnode_all_df` and everything it was made from.
#'
#' One row per scanned node, carrying the node's date and inferred state, the
#' tips below it, the predicted antigenic substitutions, and an observed
#' mutation set.
#'
#' The node set is decided by which nodes appear in the antigenicity file
#' (129 on the current data), not by `find_deep_nodes()`.
#'
#' @param tip_mutations How `mutation_real` is derived from the descendant
#'   tips, which is the one real judgement call in this pipeline. A node has
#'   many descendant tips, each with its own mutations relative to RefSeq.
#'   "first" (default) takes one representative tip and reproduces the
#'     original script exactly. Be aware of what it is: a single arbitrary
#'     tip, chosen as the earliest row in the observed-mutations FILE rather
#'     than anything about the tree, and carrying that tip's private
#'     substitutions alongside the node's own. It is kept as the default only
#'     so existing results stay reproducible.
#'   "shared" takes the intersection across all descendant tips, which is a
#'     much closer estimate of what the node itself carried. Prefer this for
#'     new analyses, and expect smaller mutation sets.
#'   "union" takes every mutation seen anywhere below the node.
noro_deepnode <- function(tree         = NORO_PATHS$tree,
                          antigenicity = NORO_PATHS$antigenicity,
                          mutations    = NORO_PATHS$mutations,
                          mrsd         = NORO_MRSD,
                          sa_min       = NORO_SA_MIN,
                          tip_mutations = c("first", "shared", "union")) {

  tip_mutations <- match.arg(tip_mutations)

  td   <- if (inherits(tree, "treedata")) tree else read.beast(tree)
  off  <- node_offspring(td, mrsd = mrsd)
  pred <- read_antigenicity(antigenicity, sa_min = sa_min)
  obs  <- read_mutations(mutations)

  missing <- setdiff(unique(off$id), obs$id)
  if (length(missing))
    warning(length(missing), " tip(s) have no observed-mutation row, e.g. ",
            paste(head(missing, 3), collapse = ", "),
            ". They contribute character(0).", call. = FALSE)

  #  Collapse node -> tips to one row per node. Sorting by `.obs_order` first
  #  makes `first()` pick the same representative tip the original right_join
  #  did, so `id`, `id_list` and `mutation_real` all match the old output.
  by_node <- off %>%
    left_join(obs, by = "id") %>%
    mutate(mutation_real = map(mutation_real, ~ if (is.null(.x)) character(0) else .x)) %>%
    arrange(.obs_order) %>%
    group_by(node, ancestor_node, clinical_state, date) %>%
    summarise(
      #  Order matters: summarise() evaluates these in sequence, so anything
      #  reading the whole `id` column must come before `id` is reduced to a
      #  single representative at the end.
      n_tips    = n(),
      id_list   = list(id),
      offspring = first(offspring),
      mutation_real = list(switch(tip_mutations,
        first  = mutation_real[[1]],
        shared = Reduce(intersect, mutation_real),
        union  = sort(unique(unlist(mutation_real)))
      )),
      id = first(id),
      .groups = "drop"
    )

  all_df <- by_node %>%
    inner_join(antigenicity_by_node(pred),
               by = c("ancestor_node" = "virus_name")) %>%
    filter(lengths(pos) > 0) %>%
    select(node, ancestor_node, clinical_state, date, id, offspring, n_tips,
           id_list, mutation_real, pos, mutation_pred) %>%
    arrange(node)

  structure(
    list(
      tree     = td,
      mrsd     = mrsd,
      mrsd_dec = as_decimal_year(mrsd),
      sa_min   = sa_min,
      tip_mutations = tip_mutations,
      offspring = off,
      pred      = pred,
      obs       = obs,
      all_df    = all_df
    ),
    class = "noro_deepnode"
  )
}

#' The combined table. Accepts the object or passes a data frame through, so
#' every function below takes either.
deepnode_df <- function(x) if (inherits(x, "noro_deepnode")) x$all_df else x

as_tree <- function(x) if (inherits(x, "noro_deepnode")) x$tree else x

print.noro_deepnode <- function(x, ...) {
  d <- x$all_df
  cat("<noro_deepnode>\n")
  cat("  tree          :", ape::Ntip(as.phylo(x$tree)), "tips,",
      ape::Nnode(as.phylo(x$tree)), "internal nodes\n")
  cat("  mrsd          :", x$mrsd, sprintf("(%.4f)", x$mrsd_dec), "\n")
  cat("  predictions   :", nrow(x$pred), "sites over",
      n_distinct(x$pred$virus_name), "nodes; accessibility >=", x$sa_min, "\n")
  cat("  combined table:", nrow(d), "nodes x", ncol(d), "columns\n")
  cat("  node dates    :", sprintf("%.1f - %.1f", min(d$date), max(d$date)), "\n")
  cat("  states        :",
      paste(sprintf("%s %d", names(table(d$clinical_state)), table(d$clinical_state)),
            collapse = ", "), "\n")
  cat("  mutation_real :", x$tip_mutations, "tip;",
      sum(lengths(d$mutation_real)), "mutations total\n")
  cat("  mutation_pred :", sum(lengths(d$mutation_pred)), "predictions total\n")
  invisible(x)
}

#' Write the combined table both ways.
#'
#' CSV cannot hold list columns, so they are collapsed to semicolon-separated
#' strings; the RDS keeps them as lists and is what the plots read.
write_deepnode <- function(x, dir = ".", stem = "noro_deepnode_all_df") {
  d <- deepnode_df(x)
  flat <- d %>%
    mutate(across(where(is.list), ~ map_chr(.x, str_c, collapse = ";")))

  csv <- file.path(dir, str_c(stem, ".csv"))
  rds <- file.path(dir, str_c(stem, ".rds"))
  write_csv(flat, csv)
  saveRDS(d, rds)
  message("wrote ", csv, " and ", rds)
  invisible(c(csv = csv, rds = rds))
}


# ── 6. ANALYSIS ───────────────────────────────────────────────────────────

#  Long form: one row per node x mutation, with the substitution parsed out.
#  `kind` is "observed" (mutation_real, anchored to RefSeq) or "predicted"
#  (mutation_pred, anchored to the node sequence).
noro_mutations <- function(x) {
  rx <- "^([A-Z])([0-9]+)([A-Z*])$"

  deepnode_df(x) %>%
    select(node, id, date, clinical_state,
           observed = mutation_real, predicted = mutation_pred) %>%
    pivot_longer(c(observed, predicted), names_to = "kind", values_to = "mut") %>%
    unnest_longer(mut) %>%
    filter(!is.na(mut)) %>%
    mutate(
      ancestral = str_match(mut, rx)[, 2],
      position  = as.integer(str_match(mut, rx)[, 3]),
      derived   = str_match(mut, rx)[, 4],
      kind      = factor(kind, levels = c("observed", "predicted"))
    )
}

#  The ancestral residue is anchored differently in the two sets, so exact
#  string matching is only reported for reference -- `pos_aa` and `position`
#  are the defensible keys.
NORO_STRINGENCY <- c(
  exact    = "Exact string",
  pos_aa   = "Position + AA",
  position = "Position only"
)

noro_keys <- function(muts) {
  muts %>%
    mutate(
      exact    = mut,
      pos_aa   = str_c(position, derived),
      position = as.character(position)
    ) %>%
    pivot_longer(all_of(names(NORO_STRINGENCY)),
                 names_to = "stringency", values_to = "key") %>%
    mutate(stringency = factor(NORO_STRINGENCY[stringency],
                               levels = NORO_STRINGENCY))
}

#  Counts of distinct keys in each set and their overlap, per stringency,
#  pooled over nodes (`$pooled`) and per node (`$per_node`).
noro_hits <- function(x) {
  keyed <- noro_mutations(x) %>% noro_keys()

  pooled <- keyed %>%
    group_by(stringency, kind) %>%
    summarise(keys = list(unique(key)), .groups = "drop") %>%
    pivot_wider(names_from = kind, values_from = keys) %>%
    mutate(
      shared    = map2_int(observed, predicted, ~ length(intersect(.x, .y))),
      observed  = lengths(observed),
      predicted = lengths(predicted)
    ) %>%
    select(stringency, observed, predicted, shared)

  per_node <- keyed %>%
    group_by(stringency, node) %>%
    summarise(
      n_shared = length(intersect(key[kind == "observed"], key[kind == "predicted"])),
      .groups = "drop"
    ) %>%
    group_by(stringency) %>%
    summarise(
      nodes_total = n(),
      nodes_hit   = sum(n_shared > 0),
      hit_events  = sum(n_shared),
      .groups = "drop"
    )

  list(pooled = pooled, per_node = per_node)
}


