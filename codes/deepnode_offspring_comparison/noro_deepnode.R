#  ──────────────────────────────────────────────────────────────────────────
#  Norovirus GII.4 VP1: deep nodes, node offspring, predicted antigenic
#  substitutions, and the combined table `noro_deepnode_all_df`.
#
#  Consolidates tree_deepnodes_v1.R (deep nodes + node offspring),
#  noro_deepnode_commented.R (the cna -> combined-table pipeline) and
#  noro_plots.R (the analysis and figures) into one script.
#
#  ── 0. Files ──────────────────────────────────────────────────────────────
#
#  All of these sit beside this script, so it runs with no edits and no
#  arguments from a clean copy of the folder.
#
#    INPUTS
#      noro_gii4_vp1_mcc.tree                         BEAST MCC tree, 1183 tips
#      combined_norovirus_antigenicity_all_nodes.csv  EpAL x ESM-2 scan, 1.4M rows
#      noro_mutation_1183.csv                         observed mutations per sequence
#
#    OUTPUTS, all regenerated by the calls in section 4
#      noro_deepnode_all_df.rds        the combined table, list columns intact
#      noro_deepnode_all_df.csv        the same, list columns as "a;b;c"
#      noro_antigenicity_top_sites.csv one row per surviving (node, position)
#      noro_node_offspring.csv         one row per (internal node, tip)
#
#  The RDS is what noro_plots.R reads.
#
#  ── 1. Build ──────────────────────────────────────────────────────────────
#
#    source("noro_deepnode.R")
#    x <- noro_deepnode()              # all four defaults, see NORO_PATHS
#    print(x)
#
#    noro_deepnode_all_df <- deepnode_df(x)      # the combined table
#
#  `x` is one object holding the tree, the node -> tip table, the predicted
#  substitutions, the observed per-sequence mutations, and the combined table.
#  Everything downstream takes either `x` or the combined table itself.
#
#  ── 2. Deep nodes ─────────────────────────────────────────────────────────
#
#    dn <- find_deep_nodes(x)          # $acute, $chronic, $mixed
#    deepnode_df(x) %>% filter(node %in% dn$chronic)
#
#  A "deep node" is the topmost node of a clade whose inferred state is
#  certain: no ancestor of it carries the same state. This is a SELECTOR over
#  the tree and is independent of which nodes were scanned for antigenicity --
#  only 6 of the 24 chronic deep nodes are among the 129 scanned ones. Use it
#  to subset the combined table, not to build it.
#
#  ── 3. Analyse ────────────────────────────────────────────────────────────
#
#    noro_mutations(x)                 # long: one row per node x mutation
#    noro_hits(x)                      # $pooled and $per_node overlap counts
#    plot_hit_bars(x)                  # observed / predicted / shared counts
#    plot_hit_bars(x, metric = "nodes")
#    plot_protein_map(x)               # VP1 1-540 lollipop map
#
#  ── 4. Save ───────────────────────────────────────────────────────────────
#
#    write_deepnode(x)                 # CSV (lists collapsed) + RDS (lists kept)
#
#  ── 5. Different files ────────────────────────────────────────────────────
#
#    x <- noro_deepnode(
#      tree         = "~/noro8.tree",
#      antigenicity = "~/cna_v2.csv",
#      mutations    = "~/noro_mutation_1183.csv",
#      mrsd         = "2025-03-01"
#    )
#
#  mrsd is the most recent sampling date and anchors every node date; change
#  it whenever the sequence set changes or all the dates are wrong.
#  ──────────────────────────────────────────────────────────────────────────
#
#  WHAT THE PIPELINE DOES, AND WHY IT IS BUILT THIS WAY
#
#  cna.csv is one table repeated 20x: for every (node, position) there are
#  exactly 20 rows, one per candidate amino acid, and the last block of
#  columns (the ESM-2 nominated substitution and its likelihood) is constant
#  within the group. Verified on the current file: 69,661 groups, every one
#  of size 20, one distinct ESM-2 label each, always among the 20 candidates.
#
#  So read_antigenicity() does three things in this order, and the ORDER IS
#  DELIBERATE -- do not "fix" it:
#
#    1. per (node, position), keep the candidate with the highest EpAL
#       antigenicity;
#    2. keep the site only if that top candidate IS the ESM-2 nominated
#       substitution;
#    3. keep surface-exposed sites only (accessibility >= sa_min).
#
#  Step 2 after step 1 is a consensus filter: it asks "is the most antigenic
#  substitution at this site also the most likely one?" and answers no for
#  most sites. Moving the filter before the slice would instead keep the
#  ESM-2 substitution at every site -- 52,961 rows rather than 2,770, a
#  different and much weaker question.
#
#  Column names are read POSITIONALLY. cna.csv has six duplicated header
#  names, so readr renames them to position...1, label...4, label...10 and so
#  on; those suffixes are column positions and silently shift if a column is
#  ever inserted. CNA_COLS below names all 15 by position instead.
#  ──────────────────────────────────────────────────────────────────────────

